import { describe, expect, it } from 'vitest'
import { localToMs, type DateCtx } from './dates'
import { parseSmart } from './smartdate'

const MSK = 'Europe/Moscow'
// вторник, 20 октября 2026, 15:00 по Москве
const ctx: DateCtx = { now: localToMs('2026-10-20', '15:00', MSK), tz: MSK }
const p = (s: string) => parseSmart(s, ctx)

describe('умный разбор названия', () => {
  it('без слов о сроке ничего не меняет', () => {
    expect(p('Купить воздуховоды')).toEqual({ title: 'Купить воздуховоды', day: null, time: null, tags: [] })
  })

  it('сегодня, завтра, послезавтра', () => {
    expect(p('Позвонить завтра')).toMatchObject({ title: 'Позвонить', day: '2026-10-21', time: null })
    expect(p('Сегодня оплатить счёт')).toMatchObject({ title: 'оплатить счёт', day: '2026-10-20' })
    expect(p('Отправить КП послезавтра')).toMatchObject({ title: 'Отправить КП', day: '2026-10-22' })
  })

  it('через несколько дней и недель', () => {
    expect(p('Проверить через 3 дня').day).toBe('2026-10-23')
    expect(p('Проверить через неделю').day).toBe('2026-10-27')
    expect(p('Проверить через 2 недели').day).toBe('2026-11-03')
  })

  it('день недели: ближайший будущий, сегодняшний значит следующая неделя', () => {
    expect(p('Встреча в пятницу').day).toBe('2026-10-23')
    expect(p('Встреча во вторник').day).toBe('2026-10-27')
    expect(p('Встреча в понедельник').day).toBe('2026-10-26')
  })

  it('дата словами, прошедшая в этом году уходит на следующий', () => {
    expect(p('Сдать отчёт 15 ноября')).toMatchObject({ title: 'Сдать отчёт', day: '2026-11-15' })
    expect(p('Сдать отчёт 5 октября').day).toBe('2027-10-05')
    expect(p('Сдать отчёт 5 октября 2028').day).toBe('2028-10-05')
    expect(p('Сдать отчёт 31 ноября').day).toBeNull()
  })

  it('время: 19:00, 7 вечера, 9 утра, 1 дня, 11 ночи, 18 часов', () => {
    expect(p('Созвон завтра в 19:00')).toMatchObject({ title: 'Созвон', day: '2026-10-21', time: '19:00' })
    expect(p('Созвон завтра в 7 вечера').time).toBe('19:00')
    expect(p('Созвон завтра в 9 утра').time).toBe('09:00')
    expect(p('Созвон завтра в 1 дня').time).toBe('13:00')
    expect(p('Созвон завтра в 12 дня').time).toBe('12:00')
    expect(p('Созвон завтра в 11 ночи').time).toBe('23:00')
    expect(p('Созвон завтра в 18 часов').time).toBe('18:00')
  })

  it('время без дня: сегодня, если ещё не прошло, иначе завтра', () => {
    expect(p('Позвонить в 18:30')).toMatchObject({ day: '2026-10-20', time: '18:30' })
    expect(p('Позвонить в 9:00')).toMatchObject({ day: '2026-10-21', time: '09:00' })
  })

  it('время в названии без «в» остаётся названием', () => {
    expect(p('Хаб: как продавать ai 16:00')).toEqual({ title: 'Хаб: как продавать ai 16:00', day: null, time: null, tags: [] })
  })

  it('теги через решётку', () => {
    expect(p('Позвонить #срочно завтра #объект_1')).toMatchObject({ title: 'Позвонить', day: '2026-10-21', tags: ['срочно', 'объект_1'] })
  })

  it('если от названия ничего не осталось, текст сохраняется', () => {
    expect(p('завтра')).toMatchObject({ title: 'завтра', day: '2026-10-21' })
  })

  it('неверное время не разбирается', () => {
    expect(p('Дело в 25:00').time).toBeNull()
    expect(p('Дело в 14 вечера').time).toBeNull()
  })
})
