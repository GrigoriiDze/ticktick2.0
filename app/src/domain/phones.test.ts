import { describe, expect, it } from 'vitest'
import { findPhones } from './phones'

describe('телефоны в тексте задачи', () => {
  it('находит номера в разной записи и приводит к +7', () => {
    const text = 'Позвонить Сергею +7 (900) 123-45-67, потом на склад 8 910 555 66 77 и по 89201112233'
    expect(findPhones(text).map((p) => p.href)).toEqual(['tel:+79001234567', 'tel:+79105556677', 'tel:+79201112233'])
  })

  it('один номер дважды даёт одну ссылку, текст сохраняется как написан', () => {
    const r = findPhones('8-900-123-45-67 и ещё раз +79001234567')
    expect(r).toHaveLength(1)
    expect(r[0].text).toBe('8-900-123-45-67')
  })

  it('суммы, даты и артикулы за телефон не принимаются', () => {
    expect(findPhones('Смета 1 500 000 ₽, заказ 12345678901234, счёт от 22.10.2026, 3 вентилятора')).toEqual([])
  })
})
